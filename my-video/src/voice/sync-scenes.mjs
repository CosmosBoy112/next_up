/* global console */
// Copies src/scenes/*.tsx into src/voice/scenes/ so the narrated version picks up the latest
// scene content, with overlay imports pointed at the voice overlay. Run: node src/voice/sync-scenes.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, "..", "scenes");
const to = join(here, "scenes");
mkdirSync(to, { recursive: true });

for (const name of readdirSync(from).filter((f) => f.endsWith(".tsx"))) {
  const src = readFileSync(join(from, name), "utf8")
    .replace(/from "\.\.\/ui\/overlay"/g, 'from "../overlay"')
    .replace(/from "\.\.\/(ui\/|theme|timing)/g, 'from "../../$1');
  writeFileSync(join(to, name), `// Generated by src/voice/sync-scenes.mjs from src/scenes/${name}. Edit the original.\n${src}`);
  console.log(`synced ${name}`);
}
