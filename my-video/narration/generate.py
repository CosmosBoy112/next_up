"""Generate the NextUpDemoVoice voice-over with Kokoro-82M (kokoro-onnx).

Writes one trimmed clip per line to public/narration/ and the scene lengths + cue times
to src/voice/narration.ts. Captions in the narrated version follow these cues.

Setup (once):
  python3 -m venv .venv && .venv/bin/pip install kokoro-onnx soundfile
  brew install espeak-ng
  download kokoro-v1.0.onnx and voices-v1.0.bin from
  https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
Run:
  .venv/bin/python narration/generate.py --models <dir with the two model files>
"""
import argparse, json, pathlib
import numpy as np
import soundfile as sf
from kokoro_onnx import EspeakConfig, Kokoro

ROOT = pathlib.Path(__file__).resolve().parents[1]
VOICE, SPEED, GAP = "af_heart", 1.08, 0.3

# scene id, length in seconds, [(target start within scene, spoken text, caption if different)]
SCENES = [
    ("intro", 3.0, [(0.9, "Your volunteers, covered.")]),
    ("michael", 10.0, [
        (0.3, "Hey, this is Michael. He volunteers for Valley Community Pantry's Saturday delivery run."),
        (4.4, "Cancelling used to mean a guilty group text, and hoping someone sees it."),
    ]),
    ("alice", 9.6, [
        (0.3, "And this is Alice, the event coordinator."),
        (2.6, "Every cancellation meant spreadsheets, a dozen texts,"),
        (5.2, "and asking the same reliable people until they burned out."),
    ]),
    ("title", 3.4, [(0.45, "The agent proposes. The coordinator decides.")]),
    ("scenario1", 28.0, [
        (0.4, "Michael can't make Saturday. One click."),
        (5.5, "Within seconds, the agent finds people who are free, can drive, and haven't been overworked,"),
        (11.0, "and drafts a message for each."),
        (14.0, "Every step is logged."),
        (19.0, "Nothing is sent until Alice approves."),
        (24.5, "The volunteer accepts the request, and the shift is covered."),
    ]),
    ("scenario2", 10.0, [
        (0.4, "Alice can also just ask."),
        (5.0, "The agent finds the shift and proposes only people who can drive."),
    ]),
    ("scenario3", 12.0, [
        (0.4, "It watches the forecast too. A storm on Saturday?"),
        (4.0, "The agent proposes alternatives, Alice picks one,"),
        (8.5, "and the whole crew is notified."),
    ]),
    ("results", 15.0, [
        (0.5, "On the real model, ninety-three percent of scenario runs passed.", "On the real model, 93% of scenario runs passed."),
        (4.8, "And we watch every action the agent takes:"),
        (8.4, "only real volunteers, rules enforced in code,"),
        (11.6, "every step logged, and nothing sent without approval."),
    ]),
    ("outro", 4.5, [(0.3, "NextUp. The agent does the work. The coordinator stays in charge.")]),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", required=True)
    ap.add_argument("--espeak", default="/opt/homebrew/opt/espeak-ng")
    args = ap.parse_args()
    m = pathlib.Path(args.models)
    kokoro = Kokoro(
        str(m / "kokoro-v1.0.onnx"),
        str(m / "voices-v1.0.bin"),
        espeak_config=EspeakConfig(
            lib_path=f"{args.espeak}/lib/libespeak-ng.dylib", data_path=f"{args.espeak}/share/espeak-ng-data"
        ),
    )
    out_dir = ROOT / "public" / "narration"
    out_dir.mkdir(parents=True, exist_ok=True)
    scenes, n = [], 0
    for scene_id, length, lines in SCENES:
        cues, prev_end = [], 0.0
        for target, spoken, *caption in lines:
            samples, sr = kokoro.create(spoken, voice=VOICE, speed=SPEED, lang="en-us")
            loud = np.where(np.abs(samples) > 0.01)[0]
            samples = samples[max(loud[0] - int(0.03 * sr), 0) : loud[-1] + int(0.08 * sr)]
            dur = len(samples) / sr
            at = round(max(target, prev_end + GAP), 2)
            prev_end = at + dur
            if prev_end > length - 0.15:
                print(f"WARNING {scene_id}: '{spoken[:40]}' ends at {prev_end:.2f}s, scene is {length}s")
            file = f"narration/line{n:02d}.wav"
            sf.write(ROOT / "public" / file, samples, sr)
            cues.append({"at": at, "dur": round(dur, 2), "file": file, "text": caption[0] if caption else spoken})
            print(f"{scene_id:10s} {at:5.2f}-{prev_end:5.2f} / {length:4.1f}  {spoken[:60]}")
            n += 1
        scenes.append({"id": scene_id, "seconds": length, "cues": cues})
    ts = (
        "// Generated by narration/generate.py (Kokoro-82M, voice af_heart). Re-run it instead of editing.\n"
        "export type NarrationCue = { at: number; dur: number; file: string; text: string };\n"
        "export type NarratedScene = { id: string; seconds: number; cues: NarrationCue[] };\n\n"
        f"export const NARRATION: NarratedScene[] = {json.dumps(scenes, indent=2)};\n"
    )
    (ROOT / "src" / "voice" / "narration.ts").write_text(ts)


if __name__ == "__main__":
    main()
